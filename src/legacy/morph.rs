#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn unique_surface_forms() {
        let mut seen = std::collections::HashSet::new();
        for &(jp, ko) in CONJUGATED {
            assert!(!jp.is_empty() && !ko.is_empty());
            assert!(seen.insert(jp), "duplicated form: {jp}");
        }
    }
}
