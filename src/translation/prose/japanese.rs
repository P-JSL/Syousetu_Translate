pub fn expand(source: &str) -> Cow<'_, str> {
    if ["という表現", "という言葉", "っていう言葉"]
        .iter()
        .any(|part| source.contains(part))
    {
        return Cow::Borrowed(source);
    }
    if let Some(expanded) = prohibition::expand(source) {
        return Cow::Owned(expanded);
    }
    static MATCHER: LazyLock<aho_corasick::AhoCorasick> = LazyLock::new(|| {
        aho_corasick::AhoCorasickBuilder::new()
            .match_kind(aho_corasick::MatchKind::LeftmostLongest)
            .build(RULES.iter().map(|(old, _)| old))
            .expect("static reviewed contractions")
    });
    if !MATCHER.is_match(source) {
        return intent::canonicalize(Cow::Borrowed(source));
    }
    intent::canonicalize(Cow::Owned(MATCHER.replace_all(
        source,
        &RULES.iter().map(|(_, new)| *new).collect::<Vec<_>>(),
    )))
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn extended_forms_keep_aspect_politeness_names_and_numbers() {
        for (source, expected) in [
            (
                "「もう読んじゃったけど、内容は覚えてない。」",
                "「もう読んでしまったけど、内容は覚えていない。」",
            ),
            (
                "「私は働いてないけど、姉は東京で働いてるよ。」",
                "「私は働いていないけど、姉は東京で働いているよ。」",
            ),
            (
                "「薬はまだ飲んでません。午後3時まで待ってます。」",
                "「薬はまだ飲んでいません。午後3時まで待っています。」",
            ),
            (
                "「アリスはここに住んでるけど、ボブは住んでないよ。」",
                "「アリスはここに住んでいるけど、ボブは住んでいないよ。」",
            ),
            (
                "「それは昨日見てました。でも音は聞いてません。」",
                "「それは昨日見ていました。でも音は聞いていません。」",
            ),
            (
                "「できねぇけど、また挑戦する。」",
                "「できないけど、また挑戦する。」",
            ),
        ] {
            assert_eq!(expand(source), expected);
        }
        for source in [
            "「『見ちゃダメ』という表現を説明して。」",
            "「『読んじゃった』という言葉は使わない。」",
            "「知らんぷりをしたわけじゃない。」",
            "「やばいと思ったけど、大丈夫らしいよ。」",
            "「薬を飲まなくてもいいんだよ。」",
            // Canonical Japanese did not improve these in real-model review.
            "「ドアを開けちゃダメ。中に入っちゃだめだよ！」",
            "「彼はまだ帰ってないの？」",
            "「その仕事は今はやってません。」",
            "「子供たちは外で遊んじゃったよ。」",
            "「また同じ物を買っちゃうかもしれない。」",
            "「疲れたから、先に寝ちゃうね。」",
            "「今は水を飲んでます。」",
            "「彼女はまだ私を待ってません。」",
            "「見ちゃうよ！」",
        ] {
            assert_eq!(expand(source), source);
        }
    }
    #[test]
    fn obligation_completion_and_preparation_keep_their_distinct_meanings() {
        assert_eq!(expand("薬を飲まなきゃいけない。"), "薬を飲む必要がある。");
        assert_eq!(
            expand("もう食べちゃったんだよ。"),
            "もう食べてしまったんだよ。"
        );
        assert_eq!(expand("先に読んどいて。"), "先に読んでおいて。");
        assert_eq!(expand("何も聞いてないんだよ。"), "何も聞いていないんだよ。");
        assert_eq!(expand("本を読んでるよ。"), "本を読んでいるよ。");
    }
    #[test]
    fn regular_verbs_conditionals_and_ambiguous_slang_are_never_blanket_rewritten() {
        for source in [
            "捨てる。",
            "当てる。",
            "勝てる。",
            "立てる。",
            "ホテルへ行く。",
            "君が行かなきゃ、困る。",
            "草原",
            "庭の草",
            "やばい",
            "いつか会える。",
            "それちゃう。",
        ] {
            assert_eq!(expand(source), source);
        }
    }
}
